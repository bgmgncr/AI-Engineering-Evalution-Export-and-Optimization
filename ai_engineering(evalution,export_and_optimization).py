"""**Reasoning**:
Now that the `benchmark.py` script is correctly written, I need to download the sample images (`bus.jpg` and `zidane.jpg`) into the `data_samples` directory. These images are specified in `benchmark.py` as `DEFAULT_IMAGES` and are essential for the script to run without errors.


"""

import os
import requests

# Create data_samples directory if it doesn't exist
data_samples_dir = "data_samples"
os.makedirs(data_samples_dir, exist_ok=True)

# Define image URLs and local paths
image_urls = {
    "bus.jpg": "https://ultralytics.com/images/bus.jpg",
    "zidane.jpg": "https://ultralytics.com/images/zidane.jpg"
}

# Download images
for filename, url in image_urls.items():
    filepath = os.path.join(data_samples_dir, filename)
    if not os.path.exists(filepath):
        print(f"Downloading {filename}...")
        r = requests.get(url, stream=True)
        r.raise_for_status() # Raise an exception for HTTP errors
        with open(filepath, 'wb') as f:
            for chunk in r.iter_content(chunk_size=8192):
                f.write(chunk)
        print(f"Downloaded {filename}")
    else:
        print(f"{filename} already exists, skipping download.")

print(f"Contents of {data_samples_dir}:")
get_ipython().system(f'ls {data_samples_dir}')

