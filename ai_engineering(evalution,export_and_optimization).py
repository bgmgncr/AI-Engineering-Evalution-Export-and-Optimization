"""**Reasoning**:
The ONNX benchmark has completed successfully, and the `latency_onnx.csv` and `latency_pytorch.csv` files are now available. The next step, as per the main task, is to combine these latency results, calculate the Frames Per Second (FPS) for each backend, display the combined data, and save it to a new CSV file named `combined_benchmark_results.csv` in the specified Google Drive output directory.


"""

import pandas as pd
import os

# Define the output directory in Google Drive
output_dir_drive = '/content/drive/MyDrive/Colab Notebooks/AI-Engineering(Evalution,Export and Optimization)/results/'

# Load latency results for PyTorch and ONNX
latency_pytorch_path = os.path.join(output_dir_drive, 'latency_pytorch.csv')
latency_onnx_path = os.path.join(output_dir_drive, 'latency_onnx.csv')

# Check if files exist before loading
if not os.path.exists(latency_pytorch_path):
    raise FileNotFoundError(f"PyTorch latency file not found: {latency_pytorch_path}")
if not os.path.exists(latency_onnx_path):
    raise FileNotFoundError(f"ONNX latency file not found: {latency_onnx_path}")

latency_pytorch_df = pd.read_csv(latency_pytorch_path)
latency_onnx_df = pd.read_csv(latency_onnx_path)

# Concatenate the dataframes
combined_latency_df = pd.concat([latency_pytorch_df, latency_onnx_df], ignore_index=True)

# Calculate FPS for each backend
# FPS = 1000 / mean_ms
combined_latency_df['fps'] = 1000 / combined_latency_df['mean_ms']

print("Combined Latency Results (ms) and FPS:")
print(combined_latency_df.to_markdown(index=False))

# Define the path for the combined CSV file
combined_csv_path = os.path.join(output_dir_drive, 'combined_benchmark_results.csv')

# Save the combined DataFrame to a CSV file
combined_latency_df.to_csv(combined_csv_path, index=False)
print(f"\nSaved combined benchmark results to: {combined_csv_path}")

