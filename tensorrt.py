import torch
import time
import numpy as np
import onnxruntime as ort
import pandas as pd
from PIL import Image
from ultralytics import YOLO # Import YOLO for both PyTorch and TensorRT model loading
import cv2

# =========================
# 1) Define global variables
# =========================
WARMUP = 50
RUNS = 1000
IMGSZ = 640

# =========================
# 2) Prepare input image
# =========================
# Ensure bus.jpg is present (downloaded above)
img_cv2 = cv2.imread("bus.jpg")
img_cv2 = cv2.resize(img_cv2, (IMGSZ, IMGSZ))
img_cv2 = img_cv2[:, :, ::-1] # BGR to RGB
img_cv2 = img_cv2.transpose(2, 0, 1) # HWC to CHW
img_cv2 = np.ascontiguousarray(img_cv2)
img_cv2 = img_cv2.astype(np.float32) / 255.0
img = np.expand_dims(img_cv2, 0) # Add batch dimension

# =========================
# 3) Initialize list for benchmark results
# =========================
all_benchmark_results = []

print(f"Starting iterative benchmarking for {IMGSZ}x{IMGSZ} images, {RUNS} runs per benchmark after {WARMUP} warmup runs...")

# =========================
# 4) Iterate and benchmark
# =========================
for i in range(5):
    print(f"\n--- Iteration {i+1}/5 ---")
    # Initialize metrics for the current iteration
    onnx_fps, onnx_ms = float('nan'), float('nan')
    trt_fps, trt_ms = float('nan'), float('nan')
    pytorch_fps, pytorch_ms = float('nan'), float('nan')

    # =========================
    # ONNX Forward Benchmark
    # =========================
    print("Benchmarking ONNX...")
    try:
        onnx_providers = ["CUDAExecutionProvider"] if torch.cuda.is_available() else ["CPUExecutionProvider"]
        session = ort.InferenceSession("yolov8n.onnx", providers=onnx_providers)
        input_name = session.get_inputs()[0].name

        for _ in range(WARMUP):
            _ = session.run(None, {input_name: img})

        if torch.cuda.is_available():
            torch.cuda.synchronize()
        t0 = time.perf_counter()

        for _ in range(RUNS):
            _ = session.run(None, {input_name: img})

        if torch.cuda.is_available():
            torch.cuda.synchronize()
        t1 = time.perf_counter()

        onnx_time = t1 - t0
        onnx_fps = RUNS / onnx_time
        onnx_ms = (onnx_time * 1000) / RUNS
        print(f"ONNX      -> {onnx_fps:.2f} FPS | {onnx_ms:.3f} ms/img")
    except Exception as e:
        print(f"ONNX benchmarking failed: {e}")

    # =========================
    # TensorRT Forward Benchmark
    # =========================
    print("Benchmarking TensorRT...")
    if torch.cuda.is_available():
        try:
            model_trt_yolo = YOLO("yolov8n.engine")
            tensor_input = torch.from_numpy(img).to("cuda")

            for _ in range(WARMUP):
                _ = model_trt_yolo.predict(source=tensor_input, imgsz=IMGSZ, verbose=False, device='0', conf=0.25)

            torch.cuda.synchronize()
            t0_trt = time.perf_counter()

            for _ in range(RUNS):
                _ = model_trt_yolo.predict(source=tensor_input, imgsz=IMGSZ, verbose=False, device='0', conf=0.25)

            torch.cuda.synchronize()
            t1_trt = time.perf_counter()

            trt_time = t1_trt - t0_trt
            trt_fps = RUNS / trt_time
            trt_ms = (trt_time * 1000) / RUNS
            print(f"TensorRT  -> {trt_fps:.2f} FPS | {trt_ms:.3f} ms/img")
        except RuntimeError as e:
            print(f"TensorRT benchmarking skipped due to: {e}")
        except Exception as e:
            print(f"An unexpected error occurred during TensorRT benchmarking: {e}")
    else:
        print("GPU not available for TensorRT. Skipping.")

    # =========================
    # PyTorch Forward Benchmark
    # =========================
    print("Benchmarking PyTorch...")
    try:
        model_pytorch = YOLO("yolov8n.pt")
        if torch.cuda.is_available():
            model_pytorch.to("cuda")
            pytorch_input = torch.from_numpy(img).to("cuda")
        else:
            pytorch_input = torch.from_numpy(img)

        model_pytorch.eval()

        with torch.no_grad():
            for _ in range(WARMUP):
                _ = model_pytorch(pytorch_input, verbose=False, conf=0.25)

        if torch.cuda.is_available():
            torch.cuda.synchronize()
        t0_pytorch = time.perf_counter()

        with torch.no_grad():
            for _ in range(RUNS):
                _ = model_pytorch(pytorch_input, verbose=False, conf=0.25)

        if torch.cuda.is_available():
            torch.cuda.synchronize()
        t1_pytorch = time.perf_counter()

        pytorch_time = t1_pytorch - t0_pytorch
        pytorch_fps = RUNS / pytorch_time
        pytorch_ms = (pytorch_time * 1000) / RUNS
        print(f"PyTorch   -> {pytorch_fps:.2f} FPS | {pytorch_ms:.3f} ms/img")
    except Exception as e:
        print(f"PyTorch benchmarking failed: {e}")

    # Collect results for this iteration
    iteration_results = {
        'Iteration': i + 1,
        'ONNX_FPS': onnx_fps,
        'ONNX_ms/img': onnx_ms,
        'TensorRT_FPS': trt_fps,
        'TensorRT_ms/img': trt_ms,
        'PyTorch_FPS': pytorch_fps,
        'PyTorch_ms/img': pytorch_ms
    }
    all_benchmark_results.append(iteration_results)

# =========================
# 5) Convert results to DataFrame
# =========================
iterative_benchmark_df = pd.DataFrame(all_benchmark_results)
print("\n--- Iterative Benchmark Results ---")
print(iterative_benchmark_df)

"""**Reasoning**:
The previous code block successfully executed the iterative benchmarks and stored the results in a DataFrame called `iterative_benchmark_df`. Now, I need to save each iteration's results to a separate CSV file and then list all the generated filenames to confirm the task's completion.


"""

import pandas as pd

# Assuming iterative_benchmark_df is available from the previous step

# List to store generated CSV filenames
generated_csv_files = []

print("\n--- Saving Iterative Benchmark Results to CSVs ---")

# Iterate through the DataFrame and save each iteration's results to a separate CSV
for index, row in iterative_benchmark_df.iterrows():
    iteration_num = int(row['Iteration'])
    filename = f'benchmark_results_run_{iteration_num}.csv'

    # Create a DataFrame for the current iteration's results
    # Extract relevant columns and reshape for clear CSV output
    iteration_df = pd.DataFrame({
        'Method': ['ONNX', 'TensorRT', 'PyTorch'],
        'FPS': [
            row['ONNX_FPS'],
            row['TensorRT_FPS'],
            row['PyTorch_FPS']
        ],
        'ms/img': [
            row['ONNX_ms/img'],
            row['TensorRT_ms/img'],
            row['PyTorch_ms/img']
        ]
    })

    iteration_df.set_index('Method', inplace=True)
    iteration_df.to_csv(filename)
    generated_csv_files.append(filename)
    print(f"Saved iteration {iteration_num} results to {filename}")

print("\n--- Generated CSV Files ---")
for csv_file in generated_csv_files:
    print(csv_file)

